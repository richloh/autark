const BBOX = new WeakMap<Poly, [number, number, number, number]>();
function bbox(poly: Poly) {
  let b = BBOX.get(poly);
  if (!b) {
    b = [Infinity, Infinity, -Infinity, -Infinity];
    for (const [x, y] of poly) { b[0] = Math.min(b[0], x); b[1] = Math.min(b[1], y); b[2] = Math.max(b[2], x); b[3] = Math.max(b[3], y) }
    BBOX.set(poly, b);
  }
  return b;
}

function inPoly(lon: number, lat: number, poly: Poly): boolean {
  const b = bbox(poly);
  if (lon < b[0] || lon > b[2] || lat < b[1] || lat > b[3]) return false;
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(lon: number, lat: number): boolean {
  if (ISLANDS.some((p) => inPoly(lon, lat, p))) return true;
  return CONTINENTS.some((p) => inPoly(lon, lat, p)) && !SEAS.some((p) => inPoly(lon, lat, p));
}

/* ---------------------------------------------------------------- projection */

export interface View { lon0: number; lon1: number; lat0: number; lat1: number }
export interface Projection { width: number; height: number; k: number; x: (lon: number) => number; y: (lat: number) => number; view: View }

/** Equirectangular projection with a standard parallel at the view's mid latitude (keeps Europe from looking stretched). */
export function makeProjection(view: View, width = 1000): Projection {
  const midLat = (view.lat0 + view.lat1) / 2;
  const k = Math.cos((Math.max(-60, Math.min(60, midLat)) * Math.PI) / 180);
  const sx = width / ((view.lon1 - view.lon0) * k);
  const height = Math.round((view.lat1 - view.lat0) * sx);
  return {
    width, height, k, view,
    x: (lon) => (lon - view.lon0) * k * sx,
    y: (lat) => (view.lat1 - lat) * sx,
  };
}

const DOT_CACHE = new Map<string, [number, number][]>();

/** Land dots for a view; `step` is the spacing in degrees of latitude. Cached per view. */
export function landDots(p: Projection, step: number): [number, number][] {
  const key = `${p.view.lon0},${p.view.lon1},${p.view.lat0},${p.view.lat1},${step}`;
  const hit = DOT_CACHE.get(key);
  if (hit) return hit;
  const out: [number, number][] = [];
  const { lon0, lon1, lat0, lat1 } = p.view;
  const lonStep = step / p.k;
  let row = 0;
  for (let lat = lat1 - step / 2; lat > lat0; lat -= step, row++) {
    const offset = row % 2 ? lonStep / 2 : 0; // hex-ish stagger
    for (let lon = lon0 + lonStep / 2 + offset; lon < lon1; lon += lonStep) {
      if (isLand(lon, lat)) out.push([p.x(lon), p.y(lat)]);
    }
  }
  if (DOT_CACHE.size > 12) DOT_CACHE.clear();
  DOT_CACHE.set(key, out);
  return out;
}

export const VIEWS: Record<'europe' | 'world', View> = {
  europe: { lon0: -30, lon1: 52, lat0: 35, lat1: 65 },
  world: { lon0: -170, lon1: 190, lat0: -50, lat1: 78 },
};

/** View that fits all given points with padding, snapped to a sensible aspect ratio. */
export function fitView(points: { lat: number; lon: number }[]): View {
  if (!points.length) return VIEWS.europe;
  let lon0 = Math.min(...points.map((p) => p.lon)), lon1 = Math.max(...points.map((p) => p.lon));
  let lat0 = Math.min(...points.map((p) => p.lat)), lat1 = Math.max(...points.map((p) => p.lat));
  // padding: room for pin radius all around, plus extra on the right for the labels drawn east of each pin
  const spanLon = lon1 - lon0, spanLat = lat1 - lat0;
  const padLon = Math.max(4, spanLon * 0.1), padLat = Math.max(3.5, spanLat * 0.2);
  lon0 -= padLon; lon1 += padLon + Math.max(5, spanLon * 0.12); lat0 -= padLat; lat1 += padLat;
  // keep a calm, predictable aspect between 1.8:1 and 2.2:1 (in projected units)
  const k = Math.cos((((lat0 + lat1) / 2) * Math.PI) / 180);
  const ratio = ((lon1 - lon0) * k) / (lat1 - lat0);
  if (ratio > 2.2) { const need = ((lon1 - lon0) * k) / 2.2 - (lat1 - lat0); lat0 -= need / 2; lat1 += need / 2 }
  if (ratio < 1.8) { const need = ((lat1 - lat0) * 1.8) / k - (lon1 - lon0); lon0 -= need / 2; lon1 += need / 2 }
  return { lon0, lon1, lat0: Math.max(-60, lat0), lat1: Math.min(80, lat1) };
}
